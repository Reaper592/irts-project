/** Identifiant du produit genere pour une reference de la bibliotheque. */
export function productIdForRef(ref: string): string {
  return `prd_${ref.toLowerCase().replace(/[^a-z0-9]+/g, '')}`;
}

/** Dimensions effectives d'un objet : cotes saisies, sinon dimensions nominales. */
export function itemSize(
  model3d: string,
  override: { width: number | null; height: number | null; depth: number | null },
): [number, number, number] {
  const def = objectDef(model3d);
  return [override.width ?? def.size[0], override.height ?? def.size[1], override.depth ?? def.size[2]];
}

/**
 * Nombre d'unites facturees pour un objet, deduit de ses cotes.
 * Un bar module se facture au metre, un mur LED a la dalle, une piste de danse
 * et un tapis au metre carre, une guirlande a la longueur.
 */
export function billableUnits(model3d: string, size: [number, number, number], qty: number): number {
  const [w, h, d] = size;
  switch (model3d) {
    case 'bar':
      return Math.max(1, Math.round(w));
    case 'led-wall':
      return Math.max(1, Math.round((w / 0.5) * (h / 0.5)));
    case 'dance-floor':
    case 'tapis':
      return Math.max(1, Math.round(w * d));
    case 'string-lights':
    case 'fanions':
      return Math.max(1, Math.round(w / 10));
    case 'truss':
      return Math.max(1, Math.round(w / 3));
    case 'stage-deck':
      return Math.max(1, Math.round((w * d) / 2));
    case 'stage-rail':
    case 'barrier':
    case 'palissade':
    case 'haie':
      return Math.max(1, Math.round(w / 2));
    case 'stage-skirt':
      return Math.max(1, Math.round(w));
    case 'cable-ramp':
      return Math.max(1, Math.round(w));
    case 'seating-block':
      return Math.max(1, Math.round(qty));
    default:
      return Math.max(1, Math.round(qty));
  }
}


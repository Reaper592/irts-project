/**
 * Bibliotheque d'objets du Studio.
 *
 * Chaque entree est a la fois un modele 3D et une reference commerciale : elle
 * porte ses dimensions nominales en metres et, quand l'objet se loue ou se
 * vend, la fiche produit correspondante. Le catalogue de l'application est
 * genere depuis cette liste, si bien qu'un objet pose dans une scene arrive
 * toujours dans le devis avec sa designation, ses cotes et son prix.
 */
import type { EntityId, ProductMode } from '../../core/types';

export interface ObjectProduct {
  ref: string;
  name: string;
  brand: string;
  model: string;
  /** Categorie du catalogue (domaine « catalogue » de la taxonomie). */
  category: string;
  mode: ProductMode;
  unit: string;
  entity: EntityId;
  priceDay: number;
  priceSale: number;
  cost: number;
  weightKg: number;
  powerW: number;
  specs: Record<string, string>;
}

export interface ObjectDef {
  /** Cle du modele, stockee dans `SceneItem.model3d`. */
  id: string;
  label: string;
  /** Famille — libelle d'une categorie du domaine « objet3d ». */
  family: string;
  icon: string;
  /** Dimensions nominales : largeur, hauteur, profondeur, en metres. */
  size: [number, number, number];
  /** L'objet accepte des cotes libres. */
  resizable: boolean;
  /** Hauteur d'implantation par defaut, en metres (0 = pose au sol). */
  defaultY: number;
  /** L'objet projette un faisceau lumineux. */
  beam: boolean;
  /** Couleur par defaut du materiau principal ou du faisceau. */
  color?: string;
  hint?: string;
  /** L'objet represente une quantite (dalles, sieges) pilotee par `qty`. */
  countable?: boolean;
  /** Fiche produit : absente pour les objets de decor non factures. */
  product?: ObjectProduct;
}

type P = Partial<ObjectProduct>;

/** Fabrique une fiche produit avec les valeurs par defaut de la location. */
function prod(ref: string, name: string, category: string, priceDay: number, extra: P = {}): ObjectProduct {
  return {
    ref,
    name,
    brand: extra.brand ?? 'MSR',
    model: extra.model ?? '',
    category,
    mode: extra.mode ?? 'location',
    unit: extra.unit ?? 'unité',
    entity: extra.entity ?? 'msr',
    priceDay,
    priceSale: extra.priceSale ?? 0,
    cost: extra.cost ?? Math.round(priceDay * 18),
    weightKg: extra.weightKg ?? 0,
    powerW: extra.powerW ?? 0,
    specs: extra.specs ?? {},
  };
}

